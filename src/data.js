'use strict';
/* ---------------------------------------------------------------
   Sentence specs.
   W(word, ...modifiers)   word on a horizontal line; a modifier can be
                           W(adjective, adverb) for "very small"
   VB('was sleeping', ...) verb phrase: helping verbs + main verb
   YOU()                   understood subject of a command
   P(prep, object)         prepositional phrase (a modifier)
   IO(object)              indirect object (a modifier of the verb)
   C(conj, ...items)       compound part; in a compound verb an item
                           can be { V: verb, DO: object } (own object)
   { s, clauses: [a, b], conj }   compound sentence with two clauses
   Modifier strings are single-word adjectives or adverbs.
   --------------------------------------------------------------- */
const W = (w, ...mods) => ({ w, mods });
const VB = (words, ...mods) => { const ws = words.split(' '); return { w: ws[ws.length - 1], aux: ws.slice(0, -1), mods }; };
const YOU = () => ({ w: '(you)', mods: [], understood: true });
const P = (prep, obj) => ({ prep, obj });
const IO = (obj) => ({ io: obj });
const C = (conj, ...items) => ({ conj, items });
/* Advanced parts (lessons 11 and later) */
const VBL = (verbal, words, comp, mods) => { const ws = words.split(' ');
  return Object.assign({ verbal, V: { w: ws[ws.length - 1], aux: ws.slice(0, -1), mods } }, comp || {}); };
const PT = (words, comp, ...mods) => VBL('part', words, comp, mods);   // participle phrase (a modifier)
const GR = (words, comp, ...mods) => VBL('ger', words, comp, mods);    // gerund phrase (a noun)
const INF = (words, comp, ...mods) => VBL('inf', words, comp, mods);   // infinitive phrase ("to" is added)
const NC = (intro, clause) => ({ nc: clause, intro });                 // noun clause; intro: "that", "whether", or null
const AC = (clause) => ({ ac: clause });                               // adjective clause (a modifier of a noun)
const SC = (conj, clause) => ({ sc: conj, cl: clause });               // adverb clause (a modifier of a verb)
const REL = (w, ...mods) => ({ w, mods, rel: true });                  // relative pronoun inside an adjective clause
const AP = (node) => ({ app: node });                                  // appositive (a modifier of a noun)
const ADDR = (node) => ({ ind: 'ADDR', n: node });                     // independent words: direct address,
const INTJ = (w) => ({ ind: 'INTJ', n: W(w) });                        //   interjection,
const EXPL = (w) => ({ ind: 'EXPL', n: W(w) });                        //   expletive "there",
const ABS = (node) => ({ ind: 'ABS', n: node });                       //   absolute phrase (a noun with a participle)
const ADV = (w, ...mods) => ({ w, mods, role: 'ADV' });               // adverb where the parent does not show it

